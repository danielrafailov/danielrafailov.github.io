// Builds src/travel/map.ts: the travel map's land, borders and pin positions
// as ready-to-draw SVG. Run after editing PLACES:
//
//   node scripts/build-travel-map.mjs
//
// Data: Natural Earth via world-atlas (land, country borders) and us-atlas
// (US state borders). Only the projected, clipped paths are shipped.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { geoConicConformal, geoPath } from "d3-geo";
import { feature, mesh } from "topojson-client";

const PLACES = [
  { id: "toronto", name: "Toronto", region: "Ontario", lon: -79.3832, lat: 43.6532 },
  { id: "ottawa", name: "Ottawa", region: "Ontario", lon: -75.6972, lat: 45.4215 },
  { id: "quebec", name: "Quebec City", region: "Quebec", lon: -71.208, lat: 46.8139 },
  { id: "nyc", name: "New York City", region: "Manhattan & Brooklyn", lon: -73.9857, lat: 40.7484 },
  { id: "dc", name: "Washington, D.C.", region: "", lon: -77.0369, lat: 38.9072 },
  { id: "virginia", name: "Virginia", region: "", lon: -78.6569, lat: 37.4316 },
  { id: "myrtle", name: "Myrtle Beach", region: "South Carolina", lon: -78.8867, lat: 33.6891 },
  { id: "orlando", name: "Orlando", region: "Florida", lon: -81.3792, lat: 28.5383 },
  { id: "dr", name: "Dominican Republic", region: "", lon: -70.1627, lat: 18.7357 },
];

const W = 600;
const H = 760;

const read = (p) => JSON.parse(readFileSync(new URL(`../node_modules/${p}`, import.meta.url)));
const world = read("world-atlas/countries-50m.json");
const land50 = read("world-atlas/land-50m.json");
const us = read("us-atlas/states-10m.json");

// Frame the pins with some geography around them.
const lons = PLACES.map((p) => p.lon);
const lats = PLACES.map((p) => p.lat);
const pad = { lon: 4, lat: 2.5 };
const frame = {
  type: "Polygon",
  coordinates: [
    [
      [Math.min(...lons) - pad.lon, Math.min(...lats) - pad.lat],
      [Math.max(...lons) + pad.lon, Math.min(...lats) - pad.lat],
      [Math.max(...lons) + pad.lon, Math.max(...lats) + pad.lat],
      [Math.min(...lons) - pad.lon, Math.max(...lats) + pad.lat],
      [Math.min(...lons) - pad.lon, Math.min(...lats) - pad.lat],
    ].reverse(), // clockwise for d3's spherical polygons
  ],
};

const projection = geoConicConformal()
  .parallels([20, 45])
  .rotate([76, 0])
  .fitExtent(
    [
      [0, 0],
      [W, H],
    ],
    frame,
  )
  .clipExtent([
    [0, 0],
    [W, H],
  ]);

const path = geoPath(projection).digits(1);

const land = path(feature(land50, land50.objects.land));
const countryBorders = path(mesh(world, world.objects.countries, (a, b) => a !== b));
const stateBorders = path(mesh(us, us.objects.states, (a, b) => a !== b));

const places = PLACES.map((p) => {
  const [x, y] = projection([p.lon, p.lat]);
  return { ...p, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 };
});

const out = `// Generated by scripts/build-travel-map.mjs; edit PLACES there and re-run.
// Map data: Natural Earth (public domain) via world-atlas and us-atlas.

export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};

export const landPath = ${JSON.stringify(land)};
export const countryBorderPath = ${JSON.stringify(countryBorders)};
export const stateBorderPath = ${JSON.stringify(stateBorders)};

export type Place = { id: string; name: string; region: string; lon: number; lat: number; x: number; y: number };

export const places: Place[] = ${JSON.stringify(places, null, 2)};
`;

mkdirSync(new URL("../src/travel/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/travel/map.ts", import.meta.url), out);
console.log(
  `wrote src/travel/map.ts: land ${land.length} chars, countries ${countryBorders.length}, states ${stateBorders.length}`,
);
for (const p of places) console.log(`  ${p.name.padEnd(20)} ${p.x}, ${p.y}`);
